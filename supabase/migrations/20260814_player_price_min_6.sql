-- MIN_PRICE опущен с 8 до 6 (lib/pricing.ts) — при бюджете 100 на 10
-- игроков и полу в 8 набрать больше 2-3 сильных игроков было физически
-- невозможно (средняя цена состава = 10, это уже ~55-й процентиль).
-- Более дешёвый пол освобождает бюджет под топовых игроков, не трогая
-- сами квоты/потолок (17) — см. обсуждение с реальным распределением
-- цен (559 игроков уже на полу, дефицита дешёвых нет).
alter table players drop constraint if exists players_price_check;
alter table players
  add constraint players_price_check
  check (price >= 6 and price <= 17);

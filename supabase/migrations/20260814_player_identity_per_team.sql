-- Один и тот же человек в ABL может официально играть за НЕСКОЛЬКО команд
-- одновременно (пример: Никитина Елена — за Ibasket-Eagles Team И Charlote
-- Sting). Раньше игрок в синке идентифицировался по abl user.id (сам
-- человек, один на все команды) с единственным team_id — при повторной
-- синхронизации второй команды team_id просто перевешивался на неё, и
-- человек тихо пропадал из состава первой команды.
--
-- lib/abl/sync.ts теперь ключует игрока по team_user.id (регистрация
-- человека В КОНКРЕТНОЙ команде) — так игрок на двух командах превращается
-- в две отдельные карточки, каждая копит статистику только за матчи,
-- сыгранные именно за эту команду.
--
-- Старые abl_id (по user.id) не совпадут ни с одним новым team_user.id,
-- так что следующая синхронизация просто насоздавала бы дублей поверх
-- старых записей. Стираем игроков и всё, что от них зависит — их нужно
-- пересоздать с нуля повторной синхронизацией всех дивизионов (после чего
-- потребуется заново пересчитать цены в /admin/pricing).
